"""Regenerate site/sla-catalogue.js from rules/common/sla_rules.json.

The GitHub Pages showcase must not carry its own copy of SLA values: every deadline, version, pause condition, escalation
step and guardrail shown there is read from this generated file, which is a verbatim projection of the rule catalogue.
A unit test fails if the generated file drifts from the catalogue. Run: ``python scripts/sync_site_sla.py``.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "rules" / "common" / "sla_rules.json"
TARGET = ROOT / "site" / "sla-catalogue.js"
HEADER = (
    "/* GENERATED by scripts/sync_site_sla.py from rules/common/sla_rules.json — do not edit by hand.\n"
    " * Single source of truth for every SLA value shown on this site (nothing is hardcoded in the UI). */\n"
)


def render() -> str:
    catalogue = json.loads(SOURCE.read_text(encoding="utf-8"))
    return HEADER + "window.SLA_CATALOGUE = " + json.dumps(catalogue, indent=1, ensure_ascii=False) + ";\n"


def main() -> None:
    TARGET.write_text(render(), encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
