"""Renderers for the gate report: console, GitHub-flavoured markdown, and the static-site snapshot."""

from __future__ import annotations

import json
from typing import Any

_ICON = {True: "PASS", False: "FAIL"}


def to_console(report: dict[str, Any]) -> str:
    lines = ["", "MotorClaim AI release gate", "=" * 60]
    for check in report["checks"]:
        lines.append(f"  [{_ICON[check['passed']]}] {check['label']:<26} {check['summary']}")
        for failure in check["failures"][:8]:
            lines.append(f"         x {failure}")
        if len(check["failures"]) > 8:
            lines.append(f"         ... {len(check['failures']) - 8} more failures")
        for warning in check["warnings"]:
            lines.append(f"         ! {warning}")
    open_gaps = [g for g in report["known_gaps"] if g["open"]]
    lines += ["-" * 60, f"  Tracked known gaps (non-blocking, reported every run): {len(open_gaps)}"]
    by_sev: dict[str, int] = {}
    for gap in open_gaps:
        by_sev[gap["severity"]] = by_sev.get(gap["severity"], 0) + 1
    lines.append("    " + ", ".join(f"{n} {s}" for s, n in sorted(by_sev.items())))
    lines += ["=" * 60, f"  {report['verdict']}", ""]
    return "\n".join(lines)


def to_markdown(report: dict[str, Any]) -> str:
    out = [
        f"## AI release gate: {'✅' if report['release_allowed'] else '❌'} {report['verdict'].title()}",
        "",
        "| Check | Result | Summary |",
        "|---|---|---|",
    ]
    for check in report["checks"]:
        out.append(f"| {check['label']} | {'✅ Pass' if check['passed'] else '❌ Fail'} | {check['summary']} |")
    failing = [c for c in report["checks"] if c["failures"]]
    if failing:
        out += ["", "### Blocking failures"]
        for check in failing:
            out.append(f"**{check['label']}**")
            out += [f"- {f}" for f in check["failures"][:15]]
    warnings = [w for c in report["checks"] for w in c["warnings"]]
    if warnings:
        out += ["", "### Warnings"] + [f"- {w}" for w in warnings]
    out += ["", "### Agent metrics", "", "| Agent | Metric | Value | Floor | Target |", "|---|---|---|---|---|"]
    for agent in report["agents"]:
        for name, m in agent["metrics"].items():
            bound = f"≥ {m['min']}" if m["min"] is not None else f"≤ {m['max']}"
            mark = "" if m["status"] == "pass" else " ❌"
            out.append(f"| {agent['label']} | {name} | {m['value']}{mark} | {bound} | {m['target']} |")
    open_gaps = [g for g in report["known_gaps"] if g["open"]]
    out += [
        "",
        f"### Tracked known gaps ({len(open_gaps)} open, non-blocking)",
        "",
        "| Id | Severity | Agent | Title |",
        "|---|---|---|---|",
    ]
    for gap in sorted(open_gaps, key=lambda g: (["critical", "high", "medium", "low"].index(g["severity"]), g["id"])):
        out.append(f"| {gap['id']} | {gap['severity']} | {gap['agent']} | {gap['title']} |")
    return "\n".join(out) + "\n"


def site_snapshot_js(report: dict[str, Any]) -> str:
    """Deterministic (no timestamps) so the committed snapshot only changes when behaviour changes."""
    slim = {
        "framework_version": report["framework_version"],
        "release_allowed": report["release_allowed"],
        "verdict": report["verdict"],
        "checks": [
            {
                "key": c["key"],
                "label": c["label"],
                "passed": c["passed"],
                "summary": c["summary"],
                "failures": c["failures"][:10],
                "tracked_gaps": len(c["tracked_gaps"]),
                "detail": {k: v for k, v in c["detail"].items() if k != "items"},
            }
            for c in report["checks"]
        ],
        "agents": report["agents"],
        "known_gaps": report["known_gaps"],
        "injection": report["injection"],
    }
    body = json.dumps(slim, indent=2, ensure_ascii=False, sort_keys=True)
    return f"/* Generated by `python -m evals.gate --site-snapshot`. Do not edit by hand. */\nwindow.AI_EVAL_REPORT = {body};\n"
